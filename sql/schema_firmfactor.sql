CREATE TABLE IF NOT EXISTS public.entreprises (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom text NOT NULL,
    domaine text NOT NULL UNIQUE,
    secteur text NOT NULL CHECK (secteur IN ('commerce_en_ligne', 'voyages', 'livraison_colis')),
    url_trustpilot text NOT NULL,
    note_trustpilot numeric(2, 1) CHECK (note_trustpilot BETWEEN 0 AND 5),
    nb_avis_affiche integer CHECK (nb_avis_affiche >= 0),
    derniere_collecte timestamptz
);

CREATE TABLE IF NOT EXISTS public.avis (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entreprise_id bigint NOT NULL REFERENCES public.entreprises(id),
    id_externe text NOT NULL,
    note smallint NOT NULL CHECK (note BETWEEN 1 AND 5),
    titre text,
    texte text,
    date_publication timestamptz,
    date_experience date,
    verifie boolean,
    reponse_texte text,
    reponse_date timestamptz,
    auteur_nb_avis integer CHECK (auteur_nb_avis >= 0),
    collecte_le timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT avis_entreprise_id_externe_key UNIQUE (entreprise_id, id_externe)
);

CREATE INDEX IF NOT EXISTS avis_entreprise_date_idx
    ON public.avis (entreprise_id, date_publication);

ALTER TABLE public.entreprises ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.avis ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.entreprises FROM anon, authenticated;
REVOKE ALL ON public.avis FROM anon, authenticated;
